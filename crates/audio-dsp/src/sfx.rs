//! Built-in sound effects, synthesised from scratch (no samples, no third-party recordings).
//!
//! The catalogue covers what modern (short-form, TikTok-style) edits reach for: transitions
//! (whoosh, riser, zoom-in, glitch stutter…), impacts (boom, sub drop, braam, glass break,
//! thunder, gong…), interface accents (pop, ding, toggle, cash register, phone vibrate, like…),
//! meme-style accents (record scratch, rimshot, sad trombone, airhorn, bonk, clown honk,
//! applause…) and game sounds (coin, level up, explosion, gunshot, reload, hitmarker…). Every
//! sound is original work generated by the code below (oscillators, noise, envelopes and
//! filters; no samples or recordings), so it ships under the project licence.
//!
//! [`render`] is deterministic: `variant` 0 is the canonical take; other variants change pitch,
//! timing and noise slightly (seeded), so repeated accents don't sound copy-pasted.

use crate::biquad::FilterType::{BandPass, HighPass, LowPass, Peaking};
use crate::synth::*;

/// One catalogue entry.
#[derive(Clone, Copy, Debug)]
pub struct SfxInfo {
    pub id: &'static str,
    pub label: &'static str,
    /// `transition`, `impact`, `ui`, `meme`, `game`, `rhythm`.
    pub category: &'static str,
    pub tags: &'static [&'static str],
    /// Typical use, for agents choosing a sound.
    pub hint: &'static str,
}

macro_rules! sfx {
    ($id:literal, $label:literal, $cat:literal, [$($t:literal),*], $hint:literal) => {
        SfxInfo { id: $id, label: $label, category: $cat, tags: &[$($t),*], hint: $hint }
    };
}

